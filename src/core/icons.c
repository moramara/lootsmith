#define ICON_TOTAL ((int)(sizeof ICONS / sizeof *ICONS))

int icon_count(void) {
    return ICON_TOTAL;
}
const IconSprite *icon_at(int i) {
    return (i >= 0 && i < ICON_TOTAL) ? &ICONS[i] : &ICONS[ICON_TOTAL - 1];
}

int icon_exists(const char *id) {
    if (!id || !id[0] || !strcmp(id, ICON_FALLBACK_ID)) {
        return 0;
    }
    for (int i = 0; i < ICON_TOTAL; i++) {
        if (!strcmp(ICONS[i].id, id)) {
            return 1;
        }
    }
    return 0;
}
const IconSprite *icon_find(const char *id) {
    if (id && id[0]) {
        for (int i = 0; i < ICON_TOTAL; i++) {
            if (!strcmp(ICONS[i].id, id)) {
                return &ICONS[i];
            }
        }
    }
    return &ICONS[ICON_TOTAL - 1]; /* フォールバックは常に最後のエントリ */
}
